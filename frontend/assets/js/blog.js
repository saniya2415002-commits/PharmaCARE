// 1. Article Search Filter
function searchBlog() {
    const input = document.getElementById('blogSearchInput').value.toLowerCase();
    const articles = document.querySelectorAll('.blog-post-card');

    articles.forEach(article => {
        const title = article.querySelector('h2').innerText.toLowerCase();
        if (title.includes(input)) {
            article.style.display = 'flex'; // maintain flex layout
        } else {
            article.style.display = 'none';
        }
    });
}

// 2. Open Article Modal
function readArticle(title) {
    const modal = document.getElementById('blogModal');
    const container = document.getElementById('modalArticleBody');
    const data = articlesDatabase[title];

    if (!modal || !container) return;

    if (!data) {
        // Fallback for missing article data
        container.innerHTML = `
            <h2 class="modal-article-title">${title}</h2>
            <div class="modal-paragraphs">
                <p>Detailed reading content for this article is currently being reviewed by our clinical editorial team. Please check back soon for the complete guide.</p>
            </div>
        `;
    } else {
        const paragraphsHtml = data.paragraphs.map(p => `<p>${p}</p>`).join('');
        container.innerHTML = `
            <img src="${data.image}" alt="${title}" class="modal-header-img" />
            <div class="modal-meta">
                <span><i class="far fa-calendar-alt"></i> ${data.date}</span>
                <span><i class="far fa-user"></i> ${data.author}</span>
            </div>
            <h2 class="modal-article-title">${data.modalTitle || title}</h2>
            <div class="modal-paragraphs">
                ${paragraphsHtml}
            </div>
        `;
    }

    modal.classList.add('active');
    document.body.style.overflow = 'hidden'; // lock scroll
}

// 3. Close Article Modal
function closeBlogModal() {
    const modal = document.getElementById('blogModal');
    if (modal) {
        modal.classList.remove('active');
        document.body.style.overflow = 'auto'; // unlock scroll
    }
}

// 4. Toggle Heart Like Counter
function toggleLike(element) {
    const icon = element.querySelector('i');
    const countSpan = element.querySelector('.like-count');
    let count = parseInt(countSpan.innerText);

    if (icon.classList.contains('far')) {
        icon.classList.remove('far');
        icon.classList.add('fas');
        countSpan.innerText = count + 1;
    } else {
        icon.classList.remove('fas');
        icon.classList.add('far');
        countSpan.innerText = count - 1;
    }
}

// 5. Category Filtering Action
function filterCategory(category, evt) {
    const buttons = document.querySelectorAll('.filter-btn');
    buttons.forEach(btn => btn.classList.remove('active'));
    
    const targetEvent = evt || (typeof event !== 'undefined' ? event : null);
    if (targetEvent && targetEvent.currentTarget) {
        targetEvent.currentTarget.classList.add('active');
    } else {
        buttons.forEach(btn => {
            if (btn.getAttribute('onclick') && btn.getAttribute('onclick').includes(category)) {
                btn.classList.add('active');
            }
        });
    }

    const articles = document.querySelectorAll('.blog-post-card');
    articles.forEach(article => {
        const pill = article.querySelector('.category-pill');
        const pillClass = pill ? pill.className.toLowerCase() : '';
        const pillText = pill ? pill.innerText.toLowerCase() : '';
        
        if (category === 'all' || pillClass.includes(category) || pillText.includes(category)) {
            article.style.display = 'flex';
        } else {
            article.style.display = 'none';
        }
    });
}